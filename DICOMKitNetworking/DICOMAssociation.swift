import DICOMKit
import Foundation

/// An asynchronous byte-transport for complete DICOM Upper Layer PDUs.
///
/// Implement this protocol with Network.framework, a TLS stream, or a test
/// double. The association actor owns protocol ordering; transports only move
/// complete PDUs.
public protocol DICOMULTransport: Sendable {
    func send(_ pdu: DICOMULPDU) async throws
    func receive() async throws -> DICOMULPDU
    /// Must unblock any `receive()` currently in flight, for example by causing it to
    /// throw. This is required even when the underlying primitive does not itself react
    /// to `Task` cancellation, since ``DICOMAssociation`` relies on `close()` — not
    /// cancellation — to free a `receive()` blocked past ``DICOMAssociation``'s
    /// response timeout. `NetworkDICOMULTransport.close()` satisfies this via
    /// `NWConnection.cancel()`.
    func close() async
}

/// Errors generated by the DICOM association state machine.
public enum DICOMAssociationError: Error, Sendable, Equatable {
    case notAssociated
    case rejected(DICOMAssociationRejection)
    case unexpectedPDU
    case unexpectedDIMSECommand
    case timedOut
    case aborted(source: UInt8, reason: UInt8)
    case releasedByPeer
    /// A dataset passed to ``DICOMAssociation/cStore(messageID:file:)`` is missing
    /// SOP Class UID `(0008,0016)` or SOP Instance UID `(0008,0018)`.
    case missingSOPInstanceIdentification
    /// `updatePerformedProcedureStep(messageID:contextID:sopInstanceUID:status:attributes:transferSyntax:)`
    /// was asked to move a Modality Performed Procedure Step to `.inProgress`,
    /// which N-SET may never do — a step only enters `IN PROGRESS` once, via N-CREATE.
    case invalidProcedureStepTransition
}

