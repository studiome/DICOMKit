    /// Releases an established association. This method is idempotent, including
    /// after an abort or a peer-initiated release.
    public func release() async throws {
        guard acceptance != nil else { return }
        try await transport.send(.releaseRequest)
        guard case .releaseResponse = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
        tearDown()
        await transport.close()
    }

    /// Sends A-ABORT and tears down the association locally. Per PS3.8 Table
    /// 9-26, `source` 0 identifies the DICOM UL service-user and 2 the service
    /// provider; `reason` is only meaningful for a service-provider abort. An
    /// aborted association cannot be released — a subsequent ``release()``
    /// call is a no-op.
    public func abort(source: UInt8 = 0, reason: UInt8 = 0) async throws {
        try await transport.send(.abort(source: source, reason: reason))
        tearDown()
        await transport.close()
    }

    private func tearDown() {
        acceptance = nil
        requestedPresentationContexts = []
    }

    /// Reassembles a DIMSE command set from command PDVs on `contextID`. Shared by the
    /// N-service SCU methods above, whose response handling is otherwise identical.
    private func receiveCommand(contextID: UInt8) async throws -> Data {
        var command = Data()
        while true {
            guard case .pData(let values) = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
            for value in values where value.contextID == contextID && value.isCommand {
                command.append(value.data)
                if value.isLastFragment { return command }
            }
        }
    }

    /// Reassembles a data set from data PDVs on `contextID`.
    private func receiveDataset(contextID: UInt8) async throws -> Data {
        var dataset = Data()
        while true {
            guard case .pData(let values) = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
            for value in values where value.contextID == contextID && !value.isCommand {
                dataset.append(value.data)
                if value.isLastFragment { return dataset }
            }
        }
    }

    private func pdvs(data: Data, contextID: UInt8, maximumPayloadLength: Int) -> [DICOMPDataValue] {
        if data.isEmpty { return [DICOMPDataValue(contextID: contextID, isCommand: false, isLastFragment: true, data: Data())] }
        let chunks = stride(from: 0, to: data.count, by: maximumPayloadLength).map { data.subdata(in: $0..<min($0 + maximumPayloadLength, data.count)) }
        return chunks.enumerated().map { DICOMPDataValue(contextID: contextID, isCommand: false, isLastFragment: $0.offset == chunks.count - 1, data: $0.element) }
    }

    /// Receives the next PDU, transparently handling a peer A-ABORT or
    /// A-RELEASE-RQ by tearing down the association and throwing.
    private func receivePDU() async throws -> DICOMULPDU {
        let pdu = try await receiveRawPDU()
        switch pdu {
        case .abort(let source, let reason):
            tearDown()
            await transport.close()
            throw DICOMAssociationError.aborted(source: source, reason: reason)
        case .releaseRequest:
            try await transport.send(.releaseResponse)
            tearDown()
            await transport.close()
            throw DICOMAssociationError.releasedByPeer
        default:
            return pdu
        }
    }

    private func receiveRawPDU() async throws -> DICOMULPDU {
        guard let responseTimeout else { return try await transport.receive() }
        let transport = self.transport
        do {
            return try await withThrowingTaskGroup(of: DICOMULPDU.self) { group in
                group.addTask { try await transport.receive() }
                group.addTask {
                    try await Task.sleep(for: responseTimeout)
                    throw DICOMAssociationError.timedOut
                }
                do {
                    guard let first = try await group.next() else { throw DICOMAssociationError.timedOut }
                    group.cancelAll()
                    return first
                } catch {
                    // `group.cancelAll()` alone cannot free the losing `receive()`: Network
                    // primitives like `NWConnection.receive` ignore Task cancellation, and
                    // `withThrowingTaskGroup` awaits every child before this closure may
                    // return. Close the transport here, before rethrowing, so that await
                    // happens after — not before — the transport unblocks its receiver.
                    group.cancelAll()
                    await transport.close()
                    throw error
                }
            }
        } catch {
            // A timed-out (or otherwise failed) association is dead.
            tearDown()
            throw error
        }
    }
