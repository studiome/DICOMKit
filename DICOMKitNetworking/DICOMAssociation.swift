/// A serial DICOM SCU association built on a caller-supplied PDU transport.
public actor DICOMAssociation {
    private let transport: any DICOMULTransport
    private let responseTimeout: Duration?
    private var acceptance: DICOMAssociationAcceptance?
    private var requestedPresentationContexts: [DICOMPresentationContext] = []

    /// Creates an association. A non-`nil` timeout applies to every peer PDU
    /// awaited by this actor, including association negotiation and DIMSE responses.
    public init(transport: any DICOMULTransport, responseTimeout: Duration? = nil) {
        self.transport = transport
        self.responseTimeout = responseTimeout
    }

    /// Sends A-ASSOCIATE-RQ and waits for acceptance or rejection.
    @discardableResult
    public func request(_ request: DICOMAssociationRequest) async throws -> DICOMAssociationAcceptance {
        guard acceptance == nil else { throw DICOMAssociationError.unexpectedPDU }
        requestedPresentationContexts = request.presentationContexts
        try await transport.send(.associationRequest(request))
        switch try await receivePDU() {
        case .associationAcceptance(let result): acceptance = result; return result
        case .associationRejection(let rejection): throw DICOMAssociationError.rejected(rejection)
        default: throw DICOMAssociationError.unexpectedPDU
        }
    }

    /// Waits for the peer's A-ASSOCIATE-RQ. Pass the result to ``accept(_:policy:)``
    /// to negotiate and respond. Throws ``DICOMAssociationError/unexpectedPDU`` if
    /// this association is already established or the peer sends any other PDU.
    public func receiveAssociationRequest() async throws -> DICOMAssociationRequest {
        guard acceptance == nil else { throw DICOMAssociationError.unexpectedPDU }
        guard case .associationRequest(let request) = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
        return request
    }

    /// Negotiates `request` against `policy` and sends the resulting A-ASSOCIATE-AC
    /// or A-ASSOCIATE-RJ. On acceptance, records the association state so that
    /// ``receiveRequest()``, the `respondTo…` helpers, ``presentationContextID(for:)``,
    /// and ``negotiatedRoles(for:)`` behave as they do for an SCU. On rejection, closes
    /// the transport and throws ``DICOMAssociationError/rejected(_:)`` with the
    /// rejection that was sent.
    @discardableResult
    public func accept(_ request: DICOMAssociationRequest, policy: DICOMAssociationPolicy) async throws -> DICOMAssociationAcceptance {
        switch policy.negotiate(request) {
        case .accept(let result):
            requestedPresentationContexts = request.presentationContexts
            do {
                try await transport.send(.associationAcceptance(result))
            } catch {
                await transport.close()
                throw error
            }
            acceptance = result
            return result
        case .reject(let rejection):
            do {
                try await transport.send(.associationRejection(rejection))
            } catch {
                await transport.close()
                throw error
            }
            await transport.close()
            throw DICOMAssociationError.rejected(rejection)
        }
    }

    /// Returns the negotiated presentation-context ID for an abstract syntax
    /// (normally a SOP Class UID), or `nil` when it was not accepted.
    public func presentationContextID(for abstractSyntaxUID: String) -> UInt8? {
        guard let acceptance else { return nil }
        return requestedPresentationContexts.first { requested in
            requested.abstractSyntaxUID == abstractSyntaxUID && acceptance.presentationContexts.contains { accepted in
                accepted.id == requested.id && accepted.result == .acceptance
            }
        }?.id
    }

    /// Performs a C-ECHO request and returns the DIMSE status code.
    public func cEcho(messageID: UInt16, contextID: UInt8) async throws -> DICOMDIMSEStatus {
        guard let acceptance, acceptance.presentationContexts.contains(where: { $0.id == contextID && $0.result == .acceptance }) else { throw DICOMAssociationError.notAssociated }
        let maximumPayload = max(1, Int(acceptance.maximumPDULength) - 12)
        let values = try DICOMDIMSECommand.cEchoRequest(messageID: messageID).commandPDVs(contextID: contextID, maximumPayloadLength: maximumPayload)
        try await transport.send(.pData(values))
        var command = Data()
        while true {
            guard case .pData(let received) = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
            for value in received where value.contextID == contextID && value.isCommand {
                command.append(value.data)
                if value.isLastFragment {
                    guard case .cEchoResponse(let responseID, let status) = try DICOMDIMSECommand.decodeCommandSet(command), responseID == messageID else { throw DICOMAssociationError.unexpectedDIMSECommand }
                    return status
                }
            }
        }
    }

    /// Sends a C-STORE request and its dataset using the negotiated presentation context.
    /// The dataset must already use that context's negotiated transfer syntax and excludes
    /// the Part 10 File Meta Information.
    public func cStore(messageID: UInt16, contextID: UInt8, sopClassUID: String, sopInstanceUID: String, dataset: Data) async throws -> DICOMDIMSEStatus {
        guard let acceptance, acceptance.presentationContexts.contains(where: { $0.id == contextID && $0.result == .acceptance }) else { throw DICOMAssociationError.notAssociated }
        let maximumPayload = max(1, Int(acceptance.maximumPDULength) - 12)
        let command = DICOMDIMSECommand.cStoreRequest(messageID: messageID, affectedSOPClassUID: sopClassUID, affectedSOPInstanceUID: sopInstanceUID)
        try await transport.send(.pData(try command.commandPDVs(contextID: contextID, maximumPayloadLength: maximumPayload)))
        let dataValues = pdvs(data: dataset, contextID: contextID, maximumPayloadLength: maximumPayload)
        try await transport.send(.pData(dataValues))
        var response = Data()
        while true {
            guard case .pData(let values) = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
            for value in values where value.contextID == contextID && value.isCommand {
                response.append(value.data)
                if value.isLastFragment {
                    guard case .cStoreResponse(let responseID, let status) = try DICOMDIMSECommand.decodeCommandSet(response), responseID == messageID else { throw DICOMAssociationError.unexpectedDIMSECommand }
                    return status
                }
            }
        }
    }

    /// Sends C-STORE using the accepted presentation context for `sopClassUID`.
    public func cStore(messageID: UInt16, sopClassUID: String, sopInstanceUID: String, dataset: Data) async throws -> DICOMDIMSEStatus {
        guard let contextID = presentationContextID(for: sopClassUID) else { throw DICOMAssociationError.notAssociated }
        return try await cStore(messageID: messageID, contextID: contextID, sopClassUID: sopClassUID, sopInstanceUID: sopInstanceUID, dataset: dataset)
    }

    /// Sends C-STORE for `file`, using the accepted presentation context for its
    /// SOP Class UID `(0008,0016)` and encoding its dataset in that context's
    /// negotiated transfer syntax. Throws ``DICOMAssociationError/missingSOPInstanceIdentification``
    /// if the dataset lacks SOP Class UID or SOP Instance UID `(0008,0018)`, and
    /// ``DICOMAssociationError/notAssociated`` if no context was accepted for the SOP Class.
    public func cStore(messageID: UInt16, file: DICOMFile) async throws -> DICOMDIMSEStatus {
        guard let sopClassUID = file.dataset[.sopClassUID]?.stringValue,
              let sopInstanceUID = file.dataset[.sopInstanceUID]?.stringValue else {
            throw DICOMAssociationError.missingSOPInstanceIdentification
        }
        guard let contextID = presentationContextID(for: sopClassUID),
              let negotiatedTransferSyntaxUID = acceptance?.presentationContexts.first(where: { $0.id == contextID })?.transferSyntaxUID else {
            throw DICOMAssociationError.notAssociated
        }
        let dataset = try file.encodedDatasetData(transferSyntax: TransferSyntax(uid: negotiatedTransferSyntaxUID))
        return try await cStore(messageID: messageID, contextID: contextID, sopClassUID: sopClassUID, sopInstanceUID: sopInstanceUID, dataset: dataset)
    }

    /// Performs C-FIND, collecting identifier datasets for every pending response.
    public func cFind(messageID: UInt16, contextID: UInt8, sopClassUID: String, identifier: Data) async throws -> DICOMCFindResult {
        guard let acceptance, acceptance.presentationContexts.contains(where: { $0.id == contextID && $0.result == .acceptance }) else { throw DICOMAssociationError.notAssociated }
        let maximumPayload = max(1, Int(acceptance.maximumPDULength) - 12)
        try await transport.send(.pData(try DICOMDIMSECommand.cFindRequest(messageID: messageID, affectedSOPClassUID: sopClassUID).commandPDVs(contextID: contextID, maximumPayloadLength: maximumPayload)))
        try await transport.send(.pData(pdvs(data: identifier, contextID: contextID, maximumPayloadLength: maximumPayload)))
        var identifiers: [Data] = []
        var responseCommand = Data()
        var identifierBuffer = Data()
        while true {
            guard case .pData(let values) = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
            for value in values where value.contextID == contextID {
                if value.isCommand {
                    responseCommand.append(value.data)
                    guard value.isLastFragment else { continue }
                    guard case .cFindResponse(let responseID, let status, _, _) = try DICOMDIMSECommand.decodeCommandSet(responseCommand), responseID == messageID else { throw DICOMAssociationError.unexpectedDIMSECommand }
                    responseCommand.removeAll(keepingCapacity: true)
                    if !status.isPending { return DICOMCFindResult(status: status, identifiers: identifiers) }
                } else {
                    // Each pending response includes one identifier dataset, possibly split
                    // across several PDVs; only the last carries isLastFragment. A production
                    // SCP sends the command PDU before this dataset PDU.
                    identifierBuffer.append(value.data)
                    guard value.isLastFragment else { continue }
                    identifiers.append(identifierBuffer)
                    identifierBuffer.removeAll(keepingCapacity: true)
                }
            }
        }
    }

    /// Performs C-FIND using the accepted presentation context for `sopClassUID`.
    public func cFind(messageID: UInt16, sopClassUID: String, identifier: Data) async throws -> DICOMCFindResult {
        guard let contextID = presentationContextID(for: sopClassUID) else { throw DICOMAssociationError.notAssociated }
        return try await cFind(messageID: messageID, contextID: contextID, sopClassUID: sopClassUID, identifier: identifier)
    }

    /// Performs C-MOVE and returns its final DIMSE status. Pending progress
    /// responses are consumed until the peer emits a final response.
    public func cMove(messageID: UInt16, contextID: UInt8, sopClassUID: String, destination: String, identifier: Data) async throws -> DICOMCMoveResult {
        guard let acceptance, acceptance.presentationContexts.contains(where: { $0.id == contextID && $0.result == .acceptance }) else { throw DICOMAssociationError.notAssociated }
        let maximumPayload = max(1, Int(acceptance.maximumPDULength) - 12)
        let command = DICOMDIMSECommand.cMoveRequest(messageID: messageID, affectedSOPClassUID: sopClassUID, moveDestination: destination)
        try await transport.send(.pData(try command.commandPDVs(contextID: contextID, maximumPayloadLength: maximumPayload)))
        try await transport.send(.pData(pdvs(data: identifier, contextID: contextID, maximumPayloadLength: maximumPayload)))
        var response = Data()
        while true {
            guard case .pData(let values) = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
            for value in values where value.contextID == contextID && value.isCommand {
                response.append(value.data)
                guard value.isLastFragment else { continue }
                guard case .cMoveResponse(let responseID, let status, _, let subOperations, let errorComment) = try DICOMDIMSECommand.decodeCommandSet(response), responseID == messageID else { throw DICOMAssociationError.unexpectedDIMSECommand }
                response.removeAll(keepingCapacity: true)
                if !status.isPending { return DICOMCMoveResult(status: status, subOperations: subOperations, errorComment: errorComment) }
            }
        }
    }

    /// Performs C-MOVE using the accepted presentation context for `sopClassUID`.
    public func cMove(messageID: UInt16, sopClassUID: String, destination: String, identifier: Data) async throws -> DICOMCMoveResult {
        guard let contextID = presentationContextID(for: sopClassUID) else { throw DICOMAssociationError.notAssociated }
        return try await cMove(messageID: messageID, contextID: contextID, sopClassUID: sopClassUID, destination: destination, identifier: identifier)
    }

    /// Returns the accepted SCP/SCU role selection for `sopClassUID` from the
    /// A-ASSOCIATE-AC, or `nil` when the peer did not negotiate one.
    public func negotiatedRoles(for sopClassUID: String) -> DICOMRoleSelection? {
        acceptance?.roleSelections.first { $0.sopClassUID == sopClassUID }
    }

    /// Performs C-GET and returns the final DIMSE status with its sub-operation counts.
    ///
    /// Per PS3.4 C.4.3 the peer returns each matching instance as a C-STORE
    /// sub-operation on a storage presentation context, interleaved with pending
    /// C-GET responses on this context, so the caller must negotiate a storage
    /// presentation context for every SOP Class it expects to receive. Per PS3.7
    /// Annex D.3.3.4 it must also propose an SCP role in SCP/SCU role selection
    /// negotiation for each of those SOP Classes.
    ///
    /// `onStore` receives every retrieved instance and returns the DIMSE status sent
    /// back to the peer in the C-STORE-RSP. It is awaited inside this actor, so it
    /// must not call back into this same ``DICOMAssociation``.
    public func cGet(
        messageID: UInt16,
        contextID: UInt8,
        sopClassUID: String,
        identifier: Data,
        onStore: @Sendable (DICOMCStoreRequest) async -> DICOMDIMSEStatus
    ) async throws -> DICOMCGetResult {
        guard let acceptance, acceptance.presentationContexts.contains(where: { $0.id == contextID && $0.result == .acceptance }) else { throw DICOMAssociationError.notAssociated }
        let maximumPayload = max(1, Int(acceptance.maximumPDULength) - 12)
        try await transport.send(.pData(try DICOMDIMSECommand.cGetRequest(messageID: messageID, affectedSOPClassUID: sopClassUID).commandPDVs(contextID: contextID, maximumPayloadLength: maximumPayload)))
        try await transport.send(.pData(pdvs(data: identifier, contextID: contextID, maximumPayloadLength: maximumPayload)))
        var response = Data()
        var subCommands: [UInt8: Data] = [:]
        var pendingStore: (messageID: UInt16, sopClassUID: String, sopInstanceUID: String, contextID: UInt8)?
        var subDataset = Data()
        while true {
            guard case .pData(let values) = try await receivePDU() else { throw DICOMAssociationError.unexpectedPDU }
            for value in values {
                if value.contextID == contextID, value.isCommand {
                    response.append(value.data)
                    guard value.isLastFragment else { continue }
                    guard case .cGetResponse(let responseID, let status, _, let subOperations, let errorComment) = try DICOMDIMSECommand.decodeCommandSet(response), responseID == messageID else { throw DICOMAssociationError.unexpectedDIMSECommand }
                    response.removeAll(keepingCapacity: true)
                    if !status.isPending { return DICOMCGetResult(status: status, subOperations: subOperations, errorComment: errorComment) }
                } else if value.isCommand {
                    subCommands[value.contextID, default: Data()].append(value.data)
                    guard value.isLastFragment, let command = subCommands.removeValue(forKey: value.contextID) else { continue }
                    guard case .cStoreRequest(let storeID, let storeClassUID, let storeInstanceUID) = try DICOMDIMSECommand.decodeCommandSet(command) else { throw DICOMAssociationError.unexpectedDIMSECommand }
                    pendingStore = (storeID, storeClassUID, storeInstanceUID, value.contextID)
                    subDataset.removeAll(keepingCapacity: true)
                } else if let store = pendingStore, value.contextID == store.contextID {
                    subDataset.append(value.data)
                    guard value.isLastFragment else { continue }
                    let request = DICOMCStoreRequest(messageID: store.messageID, contextID: store.contextID, sopClassUID: store.sopClassUID, sopInstanceUID: store.sopInstanceUID, dataset: subDataset)
                    let status = await onStore(request)
                    try await respond(to: request, status: status)
                    pendingStore = nil
                    subDataset.removeAll(keepingCapacity: true)
                }
                // Any remaining data PDV is the C-GET response's optional failed-SOP-
                // instance-UID-list identifier, which this API does not surface.
            }
        }
    }

    /// Performs C-GET using the accepted presentation context for `sopClassUID`.
    public func cGet(
        messageID: UInt16,
        sopClassUID: String,
        identifier: Data,
        onStore: @Sendable (DICOMCStoreRequest) async -> DICOMDIMSEStatus
    ) async throws -> DICOMCGetResult {
        guard let contextID = presentationContextID(for: sopClassUID) else { throw DICOMAssociationError.notAssociated }
        return try await cGet(messageID: messageID, contextID: contextID, sopClassUID: sopClassUID, identifier: identifier, onStore: onStore)
    }

